        let parts = language.lowercased().replacingOccurrences(of: "_", with: "-").split(separator: "-").map(String.init)
        guard parts.first == "zh" else { return "en" }
        if parts.contains("hans") || (!parts.contains("hant") && parts.dropFirst().contains { ["cn", "sg", "my"].contains($0) }) {
            return "zh-hans"
        }
        return "zh"
    }

